-- Q20: Find the average consultation fee department-wise.

SELECT d.department_name, ROUND(AVG(doc.consultation_fee), 2) AS average_consultation_fee
FROM Departments AS d JOIN Doctors AS doc 
ON d.department_id = doc.department_id
GROUP BY d.department_id, d.department_name
ORDER BY average_consultation_fee DESC;

-- Q21: Find the total completed treatment revenue generated by each doctor.

SELECT doc.doctor_id, doc.doctor_name, SUM(a.treatment_cost) AS total_revenue
FROM Doctors AS doc
JOIN Appointments AS a
  ON doc.doctor_id = a.doctor_id
WHERE a.status = 'Completed'
GROUP BY doc.doctor_id, doc.doctor_name
ORDER BY total_revenue DESC;

-- Q22: Find the number of completed appointments handled by each doctor.

SELECT doc.doctor_id, doc.doctor_name,COUNT(a.appointment_id) AS completed_appointments
FROM Doctors AS doc LEFT JOIN Appointments AS a
ON doc.doctor_id = a.doctor_id
Where a.status = 'Completed'
GROUP BY doc.doctor_id, doc.doctor_name
ORDER BY completed_appointments DESC;

-- Q23: Display departments having more than one doctor.

SELECT d.department_name, COUNT(doc.doctor_id) AS doctor_count
FROM Departments AS d JOIN Doctors AS doc
ON d.department_id = doc.department_id
GROUP BY d.department_id, d.department_name
HAVING COUNT(doc.doctor_id) > 1;

-- Q24: Find the total completed treatment revenue generated by each department.

SELECT d.department_name, SUM(a.treatment_cost) AS total_revenue
FROM Departments AS d JOIN Doctors AS doc ON d.department_id = doc.department_id
JOIN Appointments AS a ON doc.doctor_id = a.doctor_id
WHERE a.status = 'Completed'
GROUP BY d.department_id, d.department_name
ORDER BY total_revenue DESC;

-- Q25: Find the average patient rating received by each doctor.

SELECT doc.doctor_id, doc.doctor_name,
       ROUND(AVG(a.rating), 2) AS average_rating
FROM Doctors AS doc
LEFT JOIN Appointments AS a
  ON doc.doctor_id = a.doctor_id
 AND a.status = 'Completed'
GROUP BY doc.doctor_id, doc.doctor_name
ORDER BY average_rating DESC;

-- Q26: Identify the city contributing the highest number of patients. Return the city and patient count.

