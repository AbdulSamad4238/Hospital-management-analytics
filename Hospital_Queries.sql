-- Q17: Find the total number of completed appointments.

SELECT COUNT(*) AS completed_appointments
FROM Appointments
WHERE status = 'Completed';

-- Q18: Find total revenue from completed appointments paid through Insurance.

SELECT SUM(treatment_cost) AS insurance_revenue
