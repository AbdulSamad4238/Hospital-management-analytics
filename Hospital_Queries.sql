-- Q28: Find the patient who has visited the hospital the highest number of times. Count completed appointments.

SELECT p.patient_id, p.patient_name, COUNT(a.appointment_id) AS visit_count
FROM Patients AS p JOIN Appointments AS a ON p.patient_id = a.patient_id
WHERE a.status = 'Completed'
GROUP BY p.patient_id, p.patient_name
ORDER BY visit_count DESC
LIMIT 1;

-- Q29: Find the most commonly treated disease among completed appointments.

SELECT disease, COUNT(*) AS treatment_count
FROM Appointments
WHERE status = 'Completed'
GROUP BY disease
ORDER BY treatment_count DESC, disease
LIMIT 1;

-- Q30: Find patients who have consulted more than one distinct doctor.

SELECT p.patient_id, p.patient_name,
       COUNT(DISTINCT a.doctor_id) AS doctors_consulted
FROM Patients AS p
JOIN Appointments AS a
  ON p.patient_id = a.patient_id
WHERE a.status = 'Completed'
GROUP BY p.patient_id, p.patient_name
HAVING COUNT(DISTINCT a.doctor_id) > 1;

-- Q31: Display doctors who have received no rating below 4. Include only doctors with at least one rated completed appointment.

SELECT doc.doctor_id, doc.doctor_name
FROM Doctors AS doc
WHERE EXISTS (
    SELECT 1
    FROM Appointments AS a
    WHERE a.doctor_id = doc.doctor_id AND a.status = 'Completed' AND a.rating IS NOT NULL
)
AND NOT EXISTS (
    SELECT 1
    FROM Appointments AS a
    WHERE a.doctor_id = doc.doctor_id AND a.status = 'Completed'AND a.rating < 4
);

-- Q32: Find departments whose average completed treatment cost is higher than the hospital-wide average completed treatment cost.

SELECT d.department_name, ROUND(AVG(a.treatment_cost), 2) AS department_avg_cost
FROM Departments AS d JOIN Doctors AS doc ON d.department_id = doc.department_id
JOIN Appointments AS a ON doc.doctor_id = a.doctor_id
WHERE a.status = 'Completed'
GROUP BY d.department_id, d.department_name
HAVING AVG(a.treatment_cost) > (
    SELECT AVG(treatment_cost)
    FROM Appointments
    WHERE status = 'Completed'
);

-- Q33: KPI: Create a hospital performance summary showing total patients, total doctors, completed appointments,
-- pending appointments, cancelled appointments, and completed treatment revenue.

SELECT
    (SELECT COUNT(*) FROM Patients) AS total_patients,
    (SELECT COUNT(*) FROM Doctors) AS total_doctors,
    (SELECT COUNT(*) FROM Appointments WHERE status = 'Completed') AS completed_appointments,
    (SELECT COUNT(*) FROM Appointments WHERE status = 'Pending') AS pending_appointments,
    (SELECT COUNT(*) FROM Appointments WHERE status = 'Cancelled') AS cancelled_appointments,
    (SELECT SUM(treatment_cost) FROM Appointments WHERE status = 'Completed') AS completed_revenue;

-- Q34: KPI: Calculate the appointment completion rate as a percentage of all appointments.

SELECT
    COUNT(CASE WHEN status = 'Completed' THEN 1 END) AS completed_appointments,
    COUNT(*) AS total_appointments,
    ROUND(100.0 * COUNT(CASE WHEN status = 'Completed' THEN 1 END) / COUNT(*), 2) AS completion_rate_pct
FROM Appointments;

-- Q35: CTE: Find patients with at least two completed visits and show their total completed treatment spend.

WITH PatientVisits AS (
    SELECT patient_id,
           COUNT(*) AS visit_count,
           SUM(treatment_cost) AS total_spend
    FROM Appointments
    WHERE status = 'Completed'
    GROUP BY patient_id
)
SELECT p.patient_id, p.patient_name,
       pv.visit_count, pv.total_spend
FROM PatientVisits AS pv
JOIN Patients AS p
  ON pv.patient_id = p.patient_id
WHERE pv.visit_count >= 2
ORDER BY pv.total_spend DESC;

-- Q36: CTE: Find the top three doctors by completed treatment revenue.

WITH DoctorRevenue AS (
    SELECT doc.doctor_id, doc.doctor_name,
           SUM(a.treatment_cost) AS total_revenue
    FROM Doctors AS doc
    JOIN Appointments AS a
      ON doc.doctor_id = a.doctor_id
    WHERE a.status = 'Completed'
    GROUP BY doc.doctor_id, doc.doctor_name
)
SELECT doctor_id, doctor_name, total_revenue
FROM DoctorRevenue
ORDER BY total_revenue DESC
LIMIT 3;

-- Q37: Window function: Rank doctors by completed treatment revenue within each department.

WITH DoctorRevenue AS (
    SELECT d.department_name,
           doc.doctor_id, doc.doctor_name,
           COALESCE(SUM(CASE WHEN a.status = 'Completed' THEN a.treatment_cost END), 0) AS total_revenue
    FROM Departments AS d
    JOIN Doctors AS doc
      ON d.department_id = doc.department_id
    LEFT JOIN Appointments AS a
      ON doc.doctor_id = a.doctor_id
    GROUP BY d.department_id, d.department_name, doc.doctor_id, doc.doctor_name
)
SELECT department_name, doctor_name, total_revenue,
       DENSE_RANK() OVER (
           PARTITION BY department_name
           ORDER BY total_revenue DESC
       ) AS revenue_rank
FROM DoctorRevenue
ORDER BY department_name, revenue_rank;

-- Q38: Window function: Show each patient's appointment date, treatment cost, 
-- and the previous completed appointment's treatment cost for that patient.

SELECT patient_id, appointment_id, appointment_date, treatment_cost,
       LAG(treatment_cost) OVER (
           PARTITION BY patient_id
           ORDER BY appointment_date, appointment_id
       ) AS previous_visit_cost
FROM Appointments
WHERE status = 'Completed'
ORDER BY patient_id, appointment_date;


